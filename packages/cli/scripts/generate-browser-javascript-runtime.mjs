import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build, transform } from "esbuild";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = join(
  packageRoot,
  "skills",
  "_shared",
  "errors-browser",
);
const target = join(
  packageRoot,
  "src",
  "generated",
  "browser-javascript-runtime.ts",
);

const sources = [
  ["browser.ts", "browser.js", "ts"],
  ["react.tsx", "react.jsx", "tsx"],
  ["vue.ts", "vue.js", "ts"],
  ["svelte.ts", "svelte.js", "ts"],
  ["artifact.ts", "artifact.js", "ts"],
  ["vite.ts", "vite.js", "ts"],
  ["webpack.ts", "webpack.mjs", "ts"],
  ["rspack.ts", "rspack.mjs", "ts"],
];

const runtime = {};
for (const [sourceName, outputName, loader] of sources) {
  const transformed = await transform(
    readFileSync(join(sourceRoot, sourceName), "utf8"),
    {
      loader,
      format: "esm",
      target: "es2022",
      jsx: "preserve",
      charset: "utf8",
      legalComments: "inline",
      sourcemap: false,
    },
  );
  runtime[outputName] = outputName.endsWith(".mjs")
    ? transformed.code.replaceAll('"./artifact"', '"./artifact.mjs"')
    : transformed.code;
}

runtime["artifact.mjs"] = runtime["artifact.js"];
runtime["vite.mjs"] = runtime["vite.js"].replaceAll(
  '"./artifact"',
  '"./artifact.mjs"',
);
const webpackCommonJs = await build({
  entryPoints: [join(sourceRoot, "webpack.ts")],
  bundle: true,
  format: "cjs",
  platform: "node",
  target: "node22",
  external: ["webpack"],
  write: false,
  sourcemap: false,
  legalComments: "inline",
});
const webpackCommonJsSource = webpackCommonJs.outputFiles[0]?.text;
if (!webpackCommonJsSource) {
  throw new Error("Could not generate the CommonJS Webpack build adapter.");
}
runtime["webpack.cjs"] = webpackCommonJsSource;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/generate-browser-javascript-runtime.mjs. Do not edit.\n` +
    `export const BROWSER_JAVASCRIPT_RUNTIME: Readonly<Record<string, string>> = ${JSON.stringify(
      runtime,
      null,
      2,
    )};\n`,
  "utf8",
);
