import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { transform } from "esbuild";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = join(
  packageRoot,
  "skills",
  "volato-vite-react",
  "assets",
  "runtime",
);
const target = join(
  packageRoot,
  "src",
  "generated",
  "browser-javascript-runtime.ts",
);

const sources = [
  ["browser.ts", "browser.js", "ts"],
  ["react.tsx", "react.jsx", "tsx"],
  ["vite.ts", "vite.js", "ts"],
];

const runtime = {};
for (const [sourceName, outputName, loader] of sources) {
  const transformed = await transform(
    readFileSync(join(sourceRoot, sourceName), "utf8"),
    {
      loader,
      format: "esm",
      target: "es2022",
      jsx: "preserve",
      charset: "utf8",
      legalComments: "inline",
      sourcemap: false,
    },
  );
  runtime[outputName] = transformed.code;
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/generate-browser-javascript-runtime.mjs. Do not edit.\n` +
    `export const BROWSER_JAVASCRIPT_RUNTIME: Readonly<Record<string, string>> = ${JSON.stringify(
      runtime,
      null,
      2,
    )};\n`,
  "utf8",
);
