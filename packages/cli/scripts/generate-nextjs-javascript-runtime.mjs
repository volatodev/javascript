import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, normalize, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build, transform } from "esbuild";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = join(
  packageRoot,
  "skills",
  "volato-nextjs",
  "assets",
  "runtime",
);
const target = join(
  packageRoot,
  "src",
  "generated",
  "nextjs-javascript-runtime.ts",
);

function filesUnder(root, prefix = "") {
  return readdirSync(join(root, prefix))
    .flatMap((name) => {
      const path = join(prefix, name);
      if (path.split(/[\\/]/).includes("__tests__")) return [];
      return statSync(join(root, path)).isDirectory()
        ? filesUnder(root, path)
        : [path];
    })
    .filter((path) => /\.(?:ts|tsx|cjs)$/.test(path))
    .sort();
}

function outputPath(sourcePath) {
  if (sourcePath.endsWith(".tsx")) return sourcePath.replace(/\.tsx$/, ".jsx");
  if (sourcePath.endsWith(".ts")) return sourcePath.replace(/\.ts$/, ".js");
  return sourcePath;
}

const sourceFiles = filesUnder(sourceRoot);
const outputsBySource = new Map(
  sourceFiles.map((sourcePath) => [
    normalize(sourcePath),
    outputPath(sourcePath),
  ]),
);

function resolveRelativeImport(fromSource, specifier) {
  const base = normalize(join(dirname(fromSource), specifier));
  for (const candidate of [
    base,
    `${base}.ts`,
    `${base}.tsx`,
    join(base, "index.ts"),
    join(base, "index.tsx"),
  ]) {
    const output = outputsBySource.get(candidate);
    if (!output) continue;
    let next = relative(dirname(outputPath(fromSource)), output).replaceAll(
      "\\",
      "/",
    );
    if (!next.startsWith(".")) next = `./${next}`;
    return next;
  }
  return specifier;
}

function rewriteRelativeImports(code, sourcePath) {
  return code.replace(
    /(\bfrom\s+)(["'])(\.[^"']+)\2/g,
    (_match, prefix, quote, specifier) =>
      `${prefix}${quote}${resolveRelativeImport(
        sourcePath,
        specifier,
      )}${quote}`,
  );
}

const runtime = {};
for (const sourcePath of sourceFiles) {
  const source = readFileSync(join(sourceRoot, sourcePath), "utf8");
  if (sourcePath.endsWith(".cjs")) {
    runtime[outputPath(sourcePath)] = source;
    continue;
  }
  const loader = sourcePath.endsWith(".tsx") ? "tsx" : "ts";
  const transformed = await transform(source, {
    loader,
    format: "esm",
    target: "es2022",
    jsx: "preserve",
    charset: "utf8",
    legalComments: "inline",
    sourcemap: false,
  });
  runtime[outputPath(sourcePath)] = rewriteRelativeImports(
    transformed.code,
    sourcePath,
  );
}

const commonJsBuild = await build({
  entryPoints: [join(sourceRoot, "withVolato.ts")],
  bundle: true,
  format: "cjs",
  platform: "node",
  target: "node18",
  write: false,
  sourcemap: false,
  legalComments: "inline",
});
const commonJsOutput = commonJsBuild.outputFiles[0]?.text;
if (!commonJsOutput) {
  throw new Error(
    "Could not generate the dependency-free CommonJS build helper.",
  );
}
// Next.js 15 transpiles a default import in next.config.ts to
// `require(...).default`; native ESM imports of CommonJS expose the whole
// namespace. Providing both shapes keeps one helper valid for TS, ESM and CJS
// configs without runtime dependencies.
const commonJsWithVolato = `${commonJsOutput}\nmodule.exports.default = module.exports;\n`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/generate-nextjs-javascript-runtime.mjs. Do not edit.\n` +
    `export const NEXTJS_JAVASCRIPT_RUNTIME: Readonly<Record<string, string>> = ${JSON.stringify(
      runtime,
      null,
      2,
    )};\n` +
    `export const NEXTJS_WITH_VOLATO_COMMONJS_RUNTIME = ${JSON.stringify(
      commonJsWithVolato,
    )};\n`,
  "utf8",
);

if (!existsSync(target))
  throw new Error("JavaScript runtime generation failed");
