import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { transform } from "esbuild";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = join(
  packageRoot,
  "skills",
  "volato-node",
  "assets",
  "runtime",
);
const target = join(
  packageRoot,
  "src",
  "generated",
  "node-javascript-runtime.ts",
);

async function transpile(sourceName, format) {
  const transformed = await transform(
    readFileSync(join(sourceRoot, sourceName), "utf8"),
    {
      loader: "ts",
      format,
      platform: "node",
      target: "node22",
      charset: "utf8",
      legalComments: "inline",
      sourcemap: false,
    },
  );
  return transformed.code;
}

const runtime = {
  "node.js": await transpile("node.ts", "esm"),
  "node.cjs": await transpile("node.ts", "cjs"),
  "express.js": (await transpile("express.ts", "esm")).replaceAll(
    '"./node.js"',
    '"./node.js"',
  ),
  "express.cjs": (await transpile("express.ts", "cjs")).replaceAll(
    '"./node.js"',
    '"./node.cjs"',
  ),
  "invocation.js": await transpile("invocation.ts", "esm"),
  "invocation.cjs": (await transpile("invocation.ts", "cjs")).replaceAll(
    '"./node.js"',
    '"./node.cjs"',
  ),
};

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/generate-node-javascript-runtime.mjs. Do not edit.\n` +
    `export const NODE_JAVASCRIPT_RUNTIME: Readonly<Record<string, string>> = ${JSON.stringify(
      runtime,
      null,
      2,
    )};\n`,
  "utf8",
);
